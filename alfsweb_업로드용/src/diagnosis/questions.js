export const categoryById = (id) => CATEGORIES.find((c) => c.id === id)

// 진단 단계에서 실제로 보여 줄 문항 목록 (업종별 추가 문항 포함)
export function questionsOf(step, category) {
  return step.questions.flatMap((q) => {
    if (q.type !== 'extra') return [q]
    const cat = categoryById(category)
    return cat ? cat.extra.map((x) => ({ ...x, id: `x_${cat.id}_${x.id}`, type: 'single', o: x.o, extraOf: cat.name })) : []
  })
}

